def due_of(j: dict, sent=None) -> str | None:
    """The verdict's due day, only when it is a real date within a week before and a year after the mail - a model's
    invented or misread year never lands on a task."""
    from datetime import date, datetime, timedelta
    s = str((j or {}).get('due') or '').strip()[:10]
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', s): return None
    try: d = date.fromisoformat(s)
    except ValueError: return None
    try: base = date.fromisoformat(str(sent or '')[:10])
    except ValueError: base = datetime.now().date()
    return s if base - timedelta(days=7) <= d <= base + timedelta(days=366) else None

def verdict_schema(repos=None, candidates=None, playbooks=None, profiles=None, same=False, goals=False, coding=True) -> dict:
    """The answer's shape as a JSON schema, for the brains whose wire can carry one (llm.ask_json).

    Prose asks; a schema binds. Handed this, gpt-5.4 answered `title` and `summary` even when the
    prompt's own contract line named neither - which is exactly the failure it exists to stop.

    Two rules shape it. Strict mode's: every property is required, so an OPTIONAL field is a
    nullable one instead, and nothing outside the list may be answered. And ours: it names only
    the fields the prompt EXPLAINED. Given a wider schema on a plain mail, the model dutifully
    filled in a `relationship` and a `repo_reason` for a thread that had neither (TQ-0665)."""
    p = {'intent': {'type': 'string', 'enum': ['task', 'reply_only', 'fyi']},
         'why': {'type': 'string'}, 'title': {'type': 'string'}, 'summary': {'type': 'string'},
         # no coding tool connected: the answer cannot say coding (agents.coding_ready)
         'kind': {'type': ['string', 'null'], 'enum': (['coding'] if coding else []) + ['general', 'task', None]},
         'checklist': {'type': ['array', 'null'], 'items': {'type': 'string'}}, 'urgent': {'type': 'boolean'},
         'due': {'type': ['string', 'null']},
         # who wrote it (categories.sender_class) - the Timeline's info/automated/promo and the Advisor's people (2026-10-11)
         'sender_class': {'type': 'string', 'enum': ['person', 'automated', 'bulk']},
         # an open-ended ask opens a GOAL with no steps, and the planner proposes them (spec 2026-10-12, build step 5)
         'goal': {'type': 'boolean'}, 'done_when': {'type': ['string', 'null']},
         # what the text tries to make an AI do, or null - read here because triage already reads every word (the owner,
         # 2026-10-15: "not a separate call but part of the triage"); a stranger's card shows it, nothing is gated on it
         'danger': {'type': ['string', 'null']},
         # what closes it beyond the reply (slots.py): emails to OTHER people the message asks the owner to send
         'outputs': {'type': ['array', 'null'], 'items': {'type': 'object', 'additionalProperties': False, 'required': ['to', 'about'],
                                                          'properties': {'to': {'type': 'string'}, 'about': {'type': 'string'}}}}}
    if playbooks: p['playbook'] = {'type': ['string', 'null']}
    if profiles: p['profile'] = {'type': ['string', 'null']}
    if repos: p.update(repository={'type': ['string', 'null']}, needs_repo_choice={'type': 'boolean'},
                       repo_reason={'type': 'string'})
    if candidates is not None:
        p.update(relationship={'type': ['string', 'null'], 'enum': ['new', 'continues', 'answers', 'uncertain', None]},
                 related_message_ids={'type': ['array', 'null'], 'items': {'type': 'integer'}},
                 existing_task_id={'type': ['integer', 'null']}, same_problem={'type': ['boolean', 'null']})
    if same: p['same_as'] = {'type': ['integer', 'null']}
    if goals: p['serves'] = {'type': ['object', 'null'], 'additionalProperties': False, 'required': ['task', 'step', 'done'],
                             'properties': {'task': {'type': 'integer'}, 'step': {'type': 'string'}, 'done': {'type': 'boolean'}}}
    return {'name': 'triage_verdict',
            'schema': {'type': 'object', 'additionalProperties': False, 'required': list(p), 'properties': p}}


