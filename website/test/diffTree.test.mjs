// THE DIFF LAID OUT LIKE A PULL REQUEST (the owner, 2026-11-08): a file list on the left by folder, the generated bundles in a group of their own
import { test } from "node:test";
import assert from "node:assert/strict";
import { fileTree, generated } from "../src/diffView.js";

test("a build's output is generated by what it is, never by this repo's folder names", () => {
  for (const p of ["site/demo/assets/AgentsPanel-BXPHDH_k.js", "taskuary/web/assets/index-3xTK3D2N.css", "package-lock.json", "web/app.min.js", "x/dist/a.js"])
    assert.ok(generated(p), p);
  for (const p of ["taskuary/outbound.py", "website/src/DiffView.jsx", "site/demo/index.html", "docs/site/connections.md"]) assert.ok(!generated(p), p);
});

test("the list puts the source first, by folder, and the generated files in one group last", () => {
  const f = (path) => ({ path, plus: 1, minus: 0 });
  const t = fileTree([f("site/demo/assets/Bolt-DsSMO0w7.js"), f("taskuary/outbound.py"), f("taskuary/agenttools.py"), f("README.md")]);
  assert.deepEqual(t.groups.map((g) => g.dir), ["", "taskuary"]);
  assert.deepEqual(t.groups[1].files.map((x) => x.name), ["outbound.py", "agenttools.py"]);
  assert.deepEqual(t.generated.map((x) => x.path), ["site/demo/assets/Bolt-DsSMO0w7.js"]);
});
